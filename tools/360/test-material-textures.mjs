import assert from 'node:assert/strict';
import * as T from 'three';
import { copyMaterialTextures } from './material-textures.js';
import { copyGeometry } from './geometry-copy.js';
const image = new T.Texture(); image.colorSpace=T.LinearSRGBColorSpace;
const source={map:image,lightMap:image,lightMapIntensity:.37,aoMap:image,aoMapIntensity:0};
const cache=new Map();const copy=t=>{if(!cache.has(t))cache.set(t,t.clone());return cache.get(t)};
const target=new T.MeshStandardMaterial();copyMaterialTextures(source,target,copy);
assert.equal(target.map.channel,0,'albedo must keep primary UVs');
assert.equal(target.lightMap.channel,1);assert.equal(target.aoMap.channel,1);
assert.equal(target.lightMapIntensity,.37);assert.equal(target.aoMapIntensity,0);
assert.equal(target.lightMap.colorSpace,T.LinearSRGBColorSpace);
assert.notEqual(target.map,target.lightMap);assert.equal(image.channel,0);
const g=new T.BufferGeometry();g.setAttribute('position',new T.Float32BufferAttribute([0,0,0,1,0,0,0,1,0],3));
g.setAttribute('uv',new T.Float32BufferAttribute([0,0,1,0,0,1],2));
g.setAttribute('uv2',new T.Float32BufferAttribute([.1,.1,.9,.1,.1,.9],2));
const modern=copyGeometry(T,g);assert.deepEqual([...modern.attributes.uv1.array],[...g.attributes.uv2.array]);
copyMaterialTextures({},target,copy);assert.equal(target.lightMap,null);assert.equal(target.aoMap,null);
console.log('Lightmap bridge: UV channel, linear color space, independent albedo UVs, zero intensity and absent-map reset passed.');
