import assert from 'node:assert/strict';
import * as T from 'three';
import { mergeGeometries } from 'three/addons/utils/BufferGeometryUtils.js';
import { batchStaticSurroundings, createPrecisionScene } from './static-batching.js';
const scene=new T.Scene(),material=new T.MeshPhysicalMaterial({color:0xaabbcc});
const make=(geometry,mat=material)=>{const mesh=new T.Mesh(geometry,mat);scene.add(mesh);return mesh};
const box=new T.BoxGeometry(1,2,3),one=make(box),two=make(box,material.clone());
two.position.set(3,0,0);two.rotation.y=.35;scene.updateMatrixWorld(true);
const positions=mesh=>{const g=mesh.geometry.index?mesh.geometry.toNonIndexed():mesh.geometry;const p=g.attributes.position,v=new T.Vector3(),result=[];for(let i=0;i<p.count;i++)result.push(v.fromBufferAttribute(p,i).applyMatrix4(mesh.matrix).toArray());if(g!==mesh.geometry)g.dispose();return result};
const expected=[...positions(one),...positions(two)];
const dense=new T.SphereGeometry(1,96,64),tree1=make(dense),tree2=make(dense);tree2.position.x=5;
const building=make(box);building.userData.primary=true;
const glass=make(box,new T.MeshPhysicalMaterial({transparent:true,opacity:.4}));
const instance=new T.InstancedMesh(box,material,3);scene.add(instance);
const materialVariant=make(box,new T.MeshPhysicalMaterial({color:0xff0000}));
scene.updateMatrixWorld(true);
const before=box.attributes.position.array.slice();
const audit=batchStaticSurroundings(T,mergeGeometries,scene);
assert.equal(audit.sources.size,1);assert.deepEqual([...audit.sources.values()][0],[one,two]);
assert.equal(audit.batchedObjects,1);assert.equal(audit.batchBoundsDelta,0);
for(const keep of [tree1,tree2,building,glass,instance,materialVariant])assert(scene.children.includes(keep));
assert.equal(tree1.geometry,tree2.geometry,'dense assets retain shared geometry');
assert.deepEqual(box.attributes.position.array,before,'source geometry untouched');
const merged=scene.children.find(m=>![tree1,tree2,building,glass,instance,materialVariant].includes(m));
const actual=positions(merged);assert.equal(actual.length,expected.length);
assert(actual.every((p,i)=>p.every((v,k)=>Math.abs(v-expected[i][k])<1e-5)),'world-space triangles preserved');
assert.equal(merged.geometry.attributes.uv.count,actual.length);
console.log('Static batching passed: exact world triangles, source unchanged, primary/transparent/instanced/dense shared assets preserved.');

scene.environmentRotation.y=.7;scene.backgroundRotation.y=.7;
const trace=createPrecisionScene(T,scene,audit.sources);
assert.equal(trace.environmentRotation.y,.7);assert.equal(trace.backgroundRotation.y,.7);
assert.equal(trace.children.length,scene.children.length+1);
assert.equal(trace.children.filter(o=>o.geometry===dense).length,2);
assert.equal(trace.children.filter(o=>o.geometry===box).length,6);
assert(!trace.children.some(o=>o.geometry===merged.geometry),'expanded raster buffer excluded from tracing');
console.log('Precision scene passed: original shared geometries, transforms and sky rotation retained.');
